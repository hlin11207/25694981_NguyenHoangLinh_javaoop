package vn.edu.javaoop.bai01;

public class ToaDo {
    private String ten;
    private double x;
    private double y;

    public ToaDo(String ten, double x, double y) {
        this.ten = ten;
        this.x = x;
        this.y = y;
    }

    public String getTen() {
        return ten;
    }

    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }
}
